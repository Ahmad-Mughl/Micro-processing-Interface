
LIST P = 18F458

#INCLUDE <P18F458.INC>

ORG 0X000
GOTO MAIN

ORG 0X008
GOTO ISR

TRUMP EQU 0X30
HARRIS EQU 0X40

;----------------ISR-------------------
ISR
	BTFSS INTCON, RBIF
	RETFIE
	
	CALL CHECK_COL

	BCF INTCON, RBIF
	RETFIE

;-----------CHECK_COL MODULE--------------

CHECK_COL
FIRST
	BTFSS PORTB, 4
	GOTO SECOND
	INCF TRUMP
	RETURN

SECOND
	BTFSS PORTB, 5
	GOTO THIRD
	INCF HARRIS
	RETURN

THIRD
	BTFSS PORTB, 6
	RETURN
	CALL CLEAR_BOTH
	RETURN 

;-------- CLEAR_BOTH MODULE------
 CLEAR_BOTH
	MOVLW 0X30
	MOVWF TRUMP
	MOVLW 0X30
	MOVWF HARRIS
	RETURN


;----------DELAY MODULE----------------
DELAY
	BANKSEL T0CON
	CLRF T0CON
	BCF T0CON, T0PS2
	BCF T0CON, T0PS1
	BCF T0CON, T0PS0
	
	MOVLW 0XDD
	MOVWF TMR0H

	MOVLW 0X00
	MOVWF TMR0L

	BSF T0CON, TMR0ON
L1
	BTFSS INTCON, TMR0IF
	GOTO L1
	BCF INTCON, TMR0IF
	BCF T0CON, TMR0ON
	RETURN

;--------LCD COMMAND MODULE------------

LCD_COMMAND
	MOVWF PORTD
	BCF PORTC, RC0
	BCF PORTC, RC1
	BSF PORTC, RC2
	CALL DELAY
	BCF PORTC, RC2
	RETURN

;--------LCD WRITE MODULE------------

LCD_WRITE
	MOVWF PORTD
	BSF PORTC, RC0
	BCF PORTC, RC1
	BSF PORTC, RC2
	CALL DELAY
	BCF PORTC, RC2
	RETURN


;-----------MAIN----------------
MAIN	
	CLRF TRISD
	CLRF TRISC

	MOVLW 0X30
	MOVWF TRUMP

	MOVLW 0X30
	MOVWF HARRIS
	
	;KEYPAD INITIALIZATION
	BANKSEL TRISB
	MOVLW 0XF0
	MOVWF TRISB

	MOVLW 0X0F
	MOVWF PORTB

	BANKSEL TRISA
	CLRF TRISA

	BANKSEL INTCON
	CLRF INTCON
	BSF INTCON, GIE
	BSF INTCON, RBIE
	;--------------------
	
	MOVFF TRUMP, PORTA
	BANKSEL PORTC
	
	BCF PORTC, RC2
	CALL DELAY

	MOVLW 0X38 
	CALL LCD_COMMAND
	CALL DELAY

	MOVLW 0X0E
	CALL LCD_COMMAND
	CALL DELAY

	MOVLW 0X01
	CALL LCD_COMMAND
	CALL DELAY
	
	MOVLW 0X06
	CALL LCD_COMMAND
	CALL DELAY

	MOVLW A'T'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'R'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'U'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'M'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'P'
	CALL LCD_WRITE
	CALL DELAY

		
	MOVLW 0X14
	CALL LCD_COMMAND
	CALL DELAY

		
	MOVLW 0X14
	CALL LCD_COMMAND
	CALL DELAY
	

	
	MOVLW 0X14
	CALL LCD_COMMAND
	CALL DELAY

	MOVF TRUMP, W
	CALL LCD_WRITE
	CALL DELAY

;-----PRINTING HARRIS--------

	MOVLW 0XC0
	CALL LCD_COMMAND
	CALL DELAY
	
	MOVLW A'H'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'A'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'R'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'R'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'I'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW A'S'
	CALL LCD_WRITE
	CALL DELAY

	MOVLW 0X14
	CALL LCD_COMMAND
	CALL DELAY

		
	MOVLW 0X14
	CALL LCD_COMMAND
	CALL DELAY
	

	MOVF HARRIS, W
	CALL LCD_WRITE
	CALL DELAY



	
AGAIN
	NOP
	GOTO AGAIN

END